package nova.kernel

/**
 * 点阵字库 —— NovaDesk 自己的字体系统。
 *
 * 每个 ASCII 字形用 5x7 点阵描述，写成字符串便于阅读和修改。
 * '#' 表示亮点。字模在需要时惰性光栅化成位图缓存。
 *
 * 这是 NovaDesk 的资产，不依赖任何系统字体。
 */
object Font {

    const val GLYPH_W = 5
    const val GLYPH_H = 7
    /** 字符单元宽度（含字间距 1px） */
    const val CELL_W = 6
    /** 字符单元高度（含行距 2px） */
    const val CELL_H = 7

    private val raw: Map<Char, Array<String>> = mapOf(
        ' ' to arrayOf("     ", "     ", "     ", "     ", "     ", "     ", "     "),
        '!' to arrayOf("  #  ", "  #  ", "  #  ", "  #  ", "  #  ", "     ", "  #  "),
        '"' to arrayOf(" # # ", " # # ", "     ", "     ", "     ", "     ", "     "),
        '#' to arrayOf(" # # ", " # # ", "#####", " # # ", "#####", " # # ", " # # "),
        '$' to arrayOf("  #  ", " ####", "# #  ", " ### ", "  # #", "#### ", "  #  "),
        '%' to arrayOf("##  #", "##  #", "   # ", "  #  ", " #   ", "#  ##", "#  ##"),
        '&' to arrayOf(" ##  ", "#  # ", "#  # ", " ##  ", "#  # ", "#   #", " ## #"),
        '\'' to arrayOf("  #  ", "  #  ", "     ", "     ", "     ", "     ", "     "),
        '(' to arrayOf("   # ", "  #  ", " #   ", " #   ", " #   ", "  #  ", "   # "),
        ')' to arrayOf(" #   ", "  #  ", "   # ", "   # ", "   # ", "  #  ", " #   "),
        '*' to arrayOf("     ", "#  # ", " ##  ", "#### ", " ##  ", "#  # ", "     "),
        '+' to arrayOf("     ", "  #  ", "  #  ", "#####", "  #  ", "  #  ", "     "),
        ',' to arrayOf("     ", "     ", "     ", "     ", "     ", "  ## ", " ##  "),
        '-' to arrayOf("     ", "     ", "     ", "#####", "     ", "     ", "     "),
        '.' to arrayOf("     ", "     ", "     ", "     ", "     ", " ##  ", " ##  "),
        '/' to arrayOf("    #", "   # ", "   # ", "  #  ", " #   ", " #   ", "#    "),
        '0' to arrayOf(" ### ", "#   #", "#  ##", "# # #", "##  #", "#   #", " ### "),
        '1' to arrayOf("  #  ", " ##  ", "  #  ", "  #  ", "  #  ", "  #  ", " ### "),
        '2' to arrayOf(" ### ", "#   #", "    #", "   # ", "  #  ", " #   ", "#####"),
        '3' to arrayOf("#####", "   # ", "  #  ", "   # ", "    #", "#   #", " ### "),
        '4' to arrayOf("   # ", "  ## ", " # # ", "#  # ", "#####", "   # ", "   # "),
        '5' to arrayOf("#####", "#    ", "#### ", "    #", "    #", "#   #", " ### "),
        '6' to arrayOf("  ## ", " #   ", "#    ", "#### ", "#   #", "#   #", " ### "),
        '7' to arrayOf("#####", "    #", "   # ", "  #  ", " #   ", " #   ", " #   "),
        '8' to arrayOf(" ### ", "#   #", "#   #", " ### ", "#   #", "#   #", " ### "),
        '9' to arrayOf(" ### ", "#   #", "#   #", " ####", "    #", "   # ", " ##  "),
        ':' to arrayOf("     ", " ##  ", " ##  ", "     ", " ##  ", " ##  ", "     "),
        ';' to arrayOf("     ", " ##  ", " ##  ", "     ", " ##  ", " ##  ", " #   "),
        '<' to arrayOf("   # ", "  #  ", " #   ", "#    ", " #   ", "  #  ", "   # "),
        '=' to arrayOf("     ", "     ", "#####", "     ", "#####", "     ", "     "),
        '>' to arrayOf(" #   ", "  #  ", "   # ", "    #", "   # ", "  #  ", " #   "),
        '?' to arrayOf(" ### ", "#   #", "    #", "   # ", "  #  ", "     ", "  #  "),
        '@' to arrayOf(" ### ", "#   #", "# ###", "# # #", "# ###", "#    ", " ### "),
        'A' to arrayOf(" ### ", "#   #", "#   #", "#####", "#   #", "#   #", "#   #"),
        'B' to arrayOf("#### ", "#   #", "#   #", "#### ", "#   #", "#   #", "#### "),
        'C' to arrayOf(" ### ", "#   #", "#    ", "#    ", "#    ", "#   #", " ### "),
        'D' to arrayOf("###  ", "#  # ", "#   #", "#   #", "#   #", "#  # ", "###  "),
        'E' to arrayOf("#####", "#    ", "#    ", "#### ", "#    ", "#    ", "#####"),
        'F' to arrayOf("#####", "#    ", "#    ", "#### ", "#    ", "#    ", "#    "),
        'G' to arrayOf(" ### ", "#   #", "#    ", "# ###", "#   #", "#   #", " ####"),
        'H' to arrayOf("#   #", "#   #", "#   #", "#####", "#   #", "#   #", "#   #"),
        'I' to arrayOf(" ### ", "  #  ", "  #  ", "  #  ", "  #  ", "  #  ", " ### "),
        'J' to arrayOf("    #", "    #", "    #", "    #", "#   #", "#   #", " ### "),
        'K' to arrayOf("#   #", "#  # ", "# #  ", "##   ", "# #  ", "#  # ", "#   #"),
        'L' to arrayOf("#    ", "#    ", "#    ", "#    ", "#    ", "#    ", "#####"),
        'M' to arrayOf("#   #", "## ##", "# # #", "# # #", "#   #", "#   #", "#   #"),
        'N' to arrayOf("#   #", "##  #", "# # #", "# # #", "#  ##", "#   #", "#   #"),
        'O' to arrayOf(" ### ", "#   #", "#   #", "#   #", "#   #", "#   #", " ### "),
        'P' to arrayOf("#### ", "#   #", "#   #", "#### ", "#    ", "#    ", "#    "),
        'Q' to arrayOf(" ### ", "#   #", "#   #", "#   #", "# # #", "#  # ", " ## #"),
        'R' to arrayOf("#### ", "#   #", "#   #", "#### ", "# #  ", "#  # ", "#   #"),
        'S' to arrayOf(" ####", "#    ", "#    ", " ### ", "    #", "    #", "#### "),
        'T' to arrayOf("#####", "  #  ", "  #  ", "  #  ", "  #  ", "  #  ", "  #  "),
        'U' to arrayOf("#   #", "#   #", "#   #", "#   #", "#   #", "#   #", " ### "),
        'V' to arrayOf("#   #", "#   #", "#   #", "#   #", "#   #", " # # ", "  #  "),
        'W' to arrayOf("#   #", "#   #", "#   #", "# # #", "# # #", "## ##", "#   #"),
        'X' to arrayOf("#   #", "#   #", " # # ", "  #  ", " # # ", "#   #", "#   #"),
        'Y' to arrayOf("#   #", "#   #", " # # ", "  #  ", "  #  ", "  #  ", "  #  "),
        'Z' to arrayOf("#####", "    #", "   # ", "  #  ", " #   ", "#    ", "#####"),
        '[' to arrayOf(" ### ", " #   ", " #   ", " #   ", " #   ", " #   ", " ### "),
        '\\' to arrayOf("#    ", " #   ", " #   ", "  #  ", "   # ", "   # ", "    #"),
        ']' to arrayOf(" ### ", "   # ", "   # ", "   # ", "   # ", "   # ", " ### "),
        '^' to arrayOf("  #  ", " # # ", "#   #", "     ", "     ", "     ", "     "),
        '_' to arrayOf("     ", "     ", "     ", "     ", "     ", "     ", "#####"),
        '`' to arrayOf(" #   ", "  #  ", "     ", "     ", "     ", "     ", "     "),
        '{' to arrayOf("   # ", "  #  ", "  #  ", " #   ", "  #  ", "  #  ", "   # "),
        '|' to arrayOf("  #  ", "  #  ", "  #  ", "  #  ", "  #  ", "  #  ", "  #  "),
        '}' to arrayOf(" #   ", "  #  ", "  #  ", "   # ", "  #  ", "  #  ", " #   "),
        '~' to arrayOf("     ", " #   ", "# # #", "   # ", "     ", "     ", "     ")
    )

    /** 未收录字符的替代字形（一个空心方块） */
    private val tofu = arrayOf("#####", "#   #", "#   #", "#   #", "#   #", "#   #", "#####")

    fun advance(ch: Char, scale: Int): Int = CELL_W * scale

    /**
     * 直接在画布上绘制字形。逐点绘制，简单可靠。
     * scale 为整数倍放大，保证像素锐利。
     */
    fun draw(c: Canvas, ch: Char, x: Int, y: Int, color: Int, scale: Int) {
        if (ch == '\n' || ch == '\r' || ch == '\t') return
        val glyph = raw[ch] ?: raw[ch.uppercaseChar()] ?: tofu
        for (row in 0 until GLYPH_H) {
            val line = glyph[row]
            for (col in 0 until GLYPH_W) {
                if (col < line.length && line[col] == '#') {
                    if (scale == 1) {
                        c.blend(x + col, y + row, color)
                    } else {
                        c.fillRect(x + col * scale, y + row * scale, scale, scale, color)
                    }
                }
            }
        }
    }
}
